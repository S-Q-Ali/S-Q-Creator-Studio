def save_trending_channels(channels: list[TrendingChannel]) -> None:
    sql = """
        INSERT INTO trending_channels (
            channel_id, title, description, thumbnail_url, subscriber_count,
            view_count, video_count, published_at, video_format, niche, category_name,
            discovered_at, viral_score, growth_rate, view_sub_ratio,
            recent_video_count, avg_views_per_video, is_newly_created, is_rapidly_growing, ai_score, last_analyzed
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(channel_id) DO UPDATE SET
            title = excluded.title, description = excluded.description,
            thumbnail_url = excluded.thumbnail_url, subscriber_count = excluded.subscriber_count,
            view_count = excluded.view_count, video_count = excluded.video_count,
            published_at = excluded.published_at, video_format = excluded.video_format,
            niche = excluded.niche, category_name = excluded.category_name,
            discovered_at = excluded.discovered_at, viral_score = excluded.viral_score,
            growth_rate = excluded.growth_rate, view_sub_ratio = excluded.view_sub_ratio,
            recent_video_count = excluded.recent_video_count,
            avg_views_per_video = excluded.avg_views_per_video,
            is_newly_created = excluded.is_newly_created,
            is_rapidly_growing = excluded.is_rapidly_growing,
            ai_score = excluded.ai_score,
            last_analyzed = trending_channels.last_analyzed
    """
    now = db.now()
    db.exec_many(
        sql,
        [
            (
                ch.channel_id,
                ch.title,
                ch.description,
                ch.thumbnail_url,
                ch.subscriber_count,
                ch.view_count,
                ch.video_count,
                ch.published_at,
                ch.video_format,
                ch.niche,
                ch.category_name,
                now,
                ch.viral_score,
                ch.growth_rate,
                ch.view_sub_ratio,
                ch.recent_video_count,
                round(ch.avg_views_per_video),
                1 if ch.is_newly_created else 0,
                1 if ch.is_rapidly_growing else 0,
                round(ch.ai_score),
                ch.last_analyzed or 0,
            )
            for ch in channels
        ],
    )


_SELECT_COLUMNS = """
    channel_id, title, description, thumbnail_url, subscriber_count,
    view_count, video_count, published_at, video_format, niche, category_name,
    viral_score, growth_rate, view_sub_ratio, recent_video_count,
    avg_views_per_video, is_newly_created, is_rapidly_growing, ai_score, last_analyzed
"""


def _row_to_trending(row: dict) -> TrendingChannel:
    return TrendingChannel(
        channel_id=row["channel_id"],
        title=row["title"],
        description=row["description"],
        thumbnail_url=row["thumbnail_url"],
        subscriber_count=row["subscriber_count"],
        view_count=row["view_count"],
        video_count=row["video_count"],
        published_at=row["published_at"],
        video_format=row["video_format"],
        niche=row["niche"],
        category_name=row["category_name"],
        viral_score=row["viral_score"],
        growth_rate=row["growth_rate"],
        view_sub_ratio=row["view_sub_ratio"],
        recent_video_count=row["recent_video_count"],
        avg_views_per_video=row["avg_views_per_video"],
        is_newly_created=bool(row["is_newly_created"]),
        is_rapidly_growing=bool(row["is_rapidly_growing"]),
        ai_score=row["ai_score"],
        last_analyzed=row["last_analyzed"],
    )


def _trending_where(video_format: str | None, niche: str | None, ai_only: bool) -> tuple[str, list]:
    conditions: list[str] = []
    params: list = []
    if video_format and video_format != "all":
        conditions.append("video_format = ?")
        params.append(video_format)
    if niche and niche != "all":
        conditions.append("niche = ?")
        params.append(niche)
    if ai_only:
        conditions.append(f"ai_score >= {AI_GENERATED_THRESHOLD}")
    where = f" WHERE {(' AND '.join(conditions))}" if conditions else ""
    return where, params


def get_trending_channels(
    video_format: str | None = None,
    niche: str | None = None,
    limit: int = 20,
    offset: int = 0,
    ai_only: bool = False,
) -> list[TrendingChannel]:
    where, params = _trending_where(video_format, niche, ai_only)
    params.extend([limit, offset])
    rows = db.all(
        f"SELECT {_SELECT_COLUMNS} FROM trending_channels{where} "
        "ORDER BY (viral_score + CASE WHEN is_newly_created = 1 THEN 5 ELSE 0 END "
        "+ CASE WHEN is_rapidly_growing = 1 THEN 10 ELSE 0 END) DESC LIMIT ? OFFSET ?",
        params,
    )
    return [_row_to_trending(row) for row in rows]


def get_trending_channel_count(
    video_format: str | None = None,
    niche: str | None = None,
    ai_only: bool = False,
) -> int:
    where, params = _trending_where(video_format, niche, ai_only)
    row = db.get(f"SELECT COUNT(*) AS count FROM trending_channels{where}", params)
    return row["count"] if row else 0


def get_trending_channel_by_id(channel_id: str) -> TrendingChannel | None:
    row = db.get(
        f"SELECT {_SELECT_COLUMNS} FROM trending_channels WHERE channel_id = ?", (channel_id,)
    )
    return _row_to_trending(row) if row else None


def log_discovery(video_format: str, niche: str, channels_found: int, searches_used: int) -> None:
    db.run(
        "INSERT INTO discovery_log (video_format, niche, channels_found, searches_used, discovered_at) "
        "VALUES (?, ?, ?, ?, ?)",
        (video_format, niche, channels_found, searches_used, db.now()),
    )


def was_niche_discovered_recently(
    video_format: str, niche: str, within_ms: int = DISCOVERY_CACHE_MS
) -> bool:
    row = db.get(
        "SELECT discovered_at FROM discovery_log "
        "WHERE video_format = ? AND niche = ? AND channels_found > 0 "
        "ORDER BY discovered_at DESC LIMIT 1",
        (video_format, niche),
    )
    if not row:
        return False
    return db.now() - row["discovered_at"] < within_ms


def get_discovery_status() -> list[dict]:
    """Latest discovery per format+niche, newest first."""
    return db.all(
        """
        SELECT d.video_format, d.niche, d.discovered_at, d.channels_found
        FROM discovery_log d
        INNER JOIN (
            SELECT video_format, niche, MAX(discovered_at) AS max_at
            FROM discovery_log GROUP BY video_format, niche
        ) latest
        ON d.video_format = latest.video_format
        AND d.niche = latest.niche
        AND d.discovered_at = latest.max_at
        ORDER BY d.discovered_at DESC
        """
    )


def refresh_all_trending(
    video_format: str | None = None,
    niche_id: str | None = None,
    *,
    cookiefile: str | None = None,
    progress: Callable[[str], None] | None = None,
    force: bool = False,
) -> dict:
    """Refresh trending data for all (or one) format/niche, honoring the 24h cache.

    Pass ``force=True`` to bypass the cache and always re-scan (used by the manual
    Discover/Update buttons so a click never silently no-ops on a fresh niche).
    """
    total_discovered = 0
    niches_scanned = 0
    total_searches = 0

    formats: list[str] = [video_format] if video_format and video_format != "all" else list(NICHES)
    for fmt in formats:
        niches: list[str]
        if niche_id and niche_id != "all":
            niches = [niche_id]
        else:
            niches = list(get_niches(fmt))
        for niche_key in niches:
            if not force and was_niche_discovered_recently(fmt, niche_key):
                continue
            try:
                channels, searches_used = discover_trending_channels(
                    fmt, niche_key, 50, cookiefile=cookiefile, progress=progress
                )
                save_trending_channels(channels)
                if channels:
                    log_discovery(fmt, niche_key, len(channels), searches_used)
                total_discovered += len(channels)
                total_searches += searches_used
                niches_scanned += 1
            except Exception as exc:
                logger.error("Failed to discover channels for %s/%s: %s", fmt, niche_key, exc)

    return {
        "discovered": total_discovered,
        "niches": niches_scanned,
        "searches_used": total_searches,
    }


def update_last_analyzed(channel_id: str, analyzed_at: int | None = None) -> None:
    db.run(
        "UPDATE trending_channels SET last_analyzed = ? WHERE channel_id = ?",
        (analyzed_at if analyzed_at is not None else db.now(), channel_id),
    )
