"""Trending channel discovery — ported from the companion research web tool's lib/trendingEngine.ts.

yt-dlp adaptation notes:
- Discovery searches are run through :func:`youtube_client.search_videos` with a
  7-day recency window (equivalent to the Data API's ``publishedAfter``).
- yt-dlp occasionally omits a channel's *total* view/video counts; when missing
  we approximate them from the videos fetched during this discovery round so the
  viral-score math stays meaningful.
- Channel join dates are not exposed by yt-dlp; ``published_at`` for a trend row
  falls back to the oldest upload date seen in the channel's own uploads flat
  list (the 7-day search window is never used, it would flag every channel as
  newly created).
"""

from __future__ import annotations

import logging
import math
import time
from collections.abc import Callable
from dataclasses import dataclass
from datetime import datetime, timezone

from s_q_ali_media_downloader.niche_research.data.niches import NICHES, get_niche, get_niches
from s_q_ali_media_downloader.niche_research.storage import db
from s_q_ali_media_downloader.niche_research.tools.youtube_client import (
    ChannelInfo,
    RateLimitError,
    VideoInfo,
    YoutubeApiError,
    fetch_channels,
    search_videos,
)

logger = logging.getLogger(__name__)

DISCOVERY_CACHE_MS = 24 * 60 * 60 * 1000  # 24h re-discovery cache
SEARCH_BUDGET = 80
TIMEOUT_BETWEEN_ATTEMPTS = 10

RAPID_GROWTH_THRESHOLD = 50
AI_GENERATED_THRESHOLD = 70

AI_CONTENT_KEYWORDS: list[str] = [
    "ai generated",
    "ai-generated",
    "generated by ai",
    "ai art",
    "ai voice",
    "ai narration",
    "ai narrated",
    "ai animated",
    "ai animation",
    "ai video",
    "ai story",
    "ai documentary",
    "ai history",
    "midjourney",
    "chatgpt",
    "stable diffusion",
    "runway ml",
    "elevenlabs",
    "eleven labs",
    "text to speech",
    "text-to-speech",
    "veo",
    "sora",
    "100% ai",
    "ai powered",
    "ai-powered",
]


@dataclass
class TrendingChannel:
    channel_id: str
    title: str
    description: str
    thumbnail_url: str
    subscriber_count: int
    view_count: int
    video_count: int
    published_at: str
    video_format: str
    niche: str
    category_name: str
    viral_score: float
    growth_rate: float
    view_sub_ratio: float
    recent_video_count: int
    avg_views_per_video: float
    is_newly_created: bool
    is_rapidly_growing: bool
    ai_score: int
    last_analyzed: int = 0


# --------------------------------------------------------------------------- #
# Scoring helpers
# --------------------------------------------------------------------------- #
def is_rapidly_growing(growth_rate: float) -> bool:
    return growth_rate >= RAPID_GROWTH_THRESHOLD


def detect_ai_generated(
    channel: ChannelInfo, videos: list[VideoInfo], is_faceless: bool = False
) -> int:
    """Best-effort AI-content likeness score (0-100). Ported verbatim."""
    haystack_parts = [channel.description]
    for video in videos[:10]:
        tags = " ".join(video.tags or [])
        haystack_parts.append(f"{video.title} {tags}")
    haystack = " ".join(haystack_parts).lower()

    hits = sum(1 for keyword in AI_CONTENT_KEYWORDS if keyword in haystack)
    score = min(hits * 25, 70)
    if is_faceless:
        score += 30
    return min(score, 100)


def _months_old(published_at: str) -> float:
    try:
        created = datetime.fromisoformat(published_at.replace("Z", "+00:00"))
    except ValueError:
        return 999.0
    if created.tzinfo is None:
        created = created.replace(tzinfo=timezone.utc)
    return max((datetime.now(timezone.utc) - created).total_seconds() / (30 * 24 * 60 * 60), 0.0)


def _math_round(value: float) -> int:
    """JavaScript Math.round semantics (half away from zero, not banker's)."""
    return math.floor(value + 0.5)


def calculate_viral_score(
    channel: ChannelInfo,
    videos: list[VideoInfo],
    growth_rate: float = 0,
    newly_created: bool = False,
) -> int:
    """Viral score (0-100). Ported verbatim from trendingEngine.ts."""
    view_sub_ratio = channel.view_count / max(channel.subscriber_count, 1)
    avg_views_per_video = channel.view_count / max(channel.video_count, 1)

    total_engagement = 0.0
    video_count = 0
    for video in videos[:10]:
        if (
            video.like_count is not None
            and video.comment_count is not None
            and video.view_count > 0
        ):
            total_engagement += (video.like_count + video.comment_count) / video.view_count
            video_count += 1
    engagement_rate = total_engagement / video_count if video_count > 0 else 0.0

    freshness_score = max(0.0, 100 - _months_old(channel.publish_date) * 5)
    growth_bonus = min(max(growth_rate, 0) / 5, 20)
    new_channel_bonus = 5 if newly_created else 0

    score = (
        min(view_sub_ratio * 30, 30)
        + min(avg_views_per_video / 10000, 25)
        + min(engagement_rate * 250, 25)
        + min(freshness_score, 20)
        + growth_bonus
        + new_channel_bonus
    )
    return _math_round(min(score, 100))


def calculate_growth_rate(videos: list[VideoInfo]) -> float:
    """Percent growth of recent-half views over older-half views."""
    if len(videos) < 2:
        return 0.0
    sorted_videos = sorted(videos, key=lambda v: v.published_at, reverse=True)
    split = (len(sorted_videos) + 1) // 2
    recent = sorted_videos[:split]
    older = sorted_videos[split:]

    recent_avg = sum(v.view_count for v in recent) / len(recent)
    older_avg = sum(v.view_count for v in older) / max(len(older), 1)

    if older_avg == 0:
        return 100.0 if recent_avg > 0 else 0.0
    return _math_round(((recent_avg - older_avg) / older_avg) * 100)


# --------------------------------------------------------------------------- #
# Discovery
# --------------------------------------------------------------------------- #
def discover_trending_channels(
    video_format: str,
    niche_id: str,
    max_results: int = 50,
    *,
    cookiefile: str | None = None,
    progress: Callable[[str], None] | None = None,
) -> tuple[list[TrendingChannel], int]:
    """Discover trending channels for one format/niche. Returns (channels, searches_used)."""
    niche = get_niche(video_format, niche_id)
    if niche is None:
        logger.error("Niche %s not found for format %s", niche_id, video_format)
        return ([], 0)

    searches_used = 0
    all_channels: dict[str, TrendingChannel] = {}

    for query in niche.queries:
        if searches_used >= SEARCH_BUDGET:
            logger.info(
                "Search budget exhausted (%s/%s), stopping discovery", searches_used, SEARCH_BUDGET
            )
            break

        try:
            videos = search_videos(
                query,
                max_results=max_results,
                days_recent=7,
                cookiefile=cookiefile,
                progress=progress,
            )
            searches_used += 1

            if video_format == "longform":
                filtered = [v for v in videos if v.duration_seconds >= 480]
            else:
                filtered = [
                    v for v in videos if v.duration_seconds == 0 or v.duration_seconds <= 60
                ]

            channel_ids = sorted({v.channel_id for v in filtered if v.channel_id})
            if not channel_ids:
                continue

            channel_video_map: dict[str, list[VideoInfo]] = {}
            for video in filtered:
                channel_video_map.setdefault(video.channel_id, []).append(video)

            channels = fetch_channels(channel_ids, cookiefile=cookiefile, progress=progress)

            for channel in channels:
                channel_videos = _dedupe_videos(channel_video_map.get(channel.channel_id, []))
                if not channel_videos:
                    continue

                total_views = sum(v.view_count for v in channel_videos)
                distinct_videos = len({v.video_id for v in channel_videos})

                view_count = channel.view_count or total_views
                video_count = channel.video_count or distinct_videos
                channel.view_count = view_count
                channel.video_count = video_count

                growth_rate = calculate_growth_rate(channel_videos)
                created_at = _channel_created_at(channel)
                newly_created = _is_newly_created(created_at)
                channel.publish_date = created_at
                viral_score = calculate_viral_score(
                    channel, channel_videos, growth_rate, newly_created
                )
                ai_score = detect_ai_generated(channel, channel_videos, niche_id == "faceless")
                view_sub_ratio = view_count / max(channel.subscriber_count, 1)
                avg_views_per_video = view_count / max(video_count, 1)

                all_channels[channel.channel_id] = TrendingChannel(
                    channel_id=channel.channel_id,
                    title=channel.title,
                    description=channel.description,
                    thumbnail_url=channel.thumbnail_url,
                    subscriber_count=channel.subscriber_count,
                    view_count=view_count,
                    video_count=video_count,
                    published_at=created_at,
                    video_format=video_format,
                    niche=niche_id,
                    category_name=niche.name,
                    viral_score=viral_score,
                    growth_rate=growth_rate,
                    view_sub_ratio=view_sub_ratio,
                    recent_video_count=distinct_videos,
                    avg_views_per_video=avg_views_per_video,
                    is_newly_created=newly_created,
                    is_rapidly_growing=is_rapidly_growing(growth_rate),
                    ai_score=ai_score,
                )
        except RateLimitError as exc:
            logger.warning(
                "Rate limited during discovery for %s/%s; retrying later: %s",
                video_format,
                niche_id,
                exc,
            )
            time.sleep(TIMEOUT_BETWEEN_ATTEMPTS)
            continue
        except YoutubeApiError as exc:
            logger.error(
                "Search error for %s/%s (query: %s): %s", video_format, niche_id, query, exc
            )
            continue

    unique = sorted(all_channels.values(), key=lambda ch: ch.viral_score, reverse=True)
    return (unique[:20], searches_used)


def _dedupe_videos(videos: list[VideoInfo]) -> list[VideoInfo]:
    seen: dict[str, VideoInfo] = {}
    for video in videos:
        seen.setdefault(video.video_id, video)
    return list(seen.values())


def _channel_created_at(channel: ChannelInfo) -> str:
    """Best-effort channel join date ISO string.

    Prefers the real ``publish_date`` when the Data API (or yt-dlp's
    ``channel_joined_date``) provides it. Otherwise falls back to the oldest
    ``upload_date`` in the channel's uploads flat list. Returns "" when
    nothing is available so freshness/new detection stay conservative.
    """
    if channel.publish_date:
        return channel.publish_date
    upload_dates = [u["upload_date"] for u in channel.uploads if u.get("upload_date")]
    if not upload_dates:
        return ""
    oldest = min(upload_dates)
    try:
        return datetime.strptime(str(oldest), "%Y%m%d").replace(tzinfo=timezone.utc).isoformat()
    except ValueError:
        return ""


def _is_newly_created(published_at: str) -> bool:
    return bool(published_at) and _months_old(published_at) <= 6


